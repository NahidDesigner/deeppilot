export function injectSprite(doc = document) {
  if (doc.getElementById('dp-sprite')) return;
  const wrap = doc.createElement('div');
  wrap.id = 'dp-sprite';
  wrap.innerHTML = spriteMarkup();
  doc.body.prepend(wrap);
}

export function icon(name, cls = '') {
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  svg.setAttribute('class', `ic ${cls}`.trim());
  svg.setAttribute('aria-hidden', 'true');
  const use = document.createElementNS(ns, 'use');
  use.setAttribute('href', `#i-${name}`);
  svg.appendChild(use);
  return svg;
}

export function fileIconName(ext) {
  if (['csv', 'tsv', 'xlsx'].includes(ext)) return 'sheet';
  if (['png', 'jpg', 'jpeg', 'webp', 'gif', 'svg', 'avif'].includes(ext)) return 'image';
  if (['pdf', 'docx', 'md', 'txt'].includes(ext)) return 'file-text';
  return 'file';
}
